-- 1. Buat tabel 'portfolios'
create table if not exists public.portfolios (
  id bigint generated by default as identity primary key,
  title text not null,
  subtitle text default '',
  category text not null check (category in ('illustration', 'chibi', 'live2d', 'skeb')),
  image_url text not null,
  is_featured boolean default false,
  tags text[] default '{}',
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 2. Aktifkan Row Level Security (RLS)
alter table public.portfolios enable row level security;

-- 3. Policy: Izinkan semua pengunjung membaca portfolio
create policy "Allow public read on portfolios"
  on public.portfolios
  for select
  using (true);

-- 4. Policy: Izinkan input, update, dan delete (menggunakan anon key dari admin)
create policy "Allow anon insert on portfolios"
  on public.portfolios
  for insert
  with check (true);

create policy "Allow anon update on portfolios"
  on public.portfolios
  for update
  using (true)
  with check (true);

create policy "Allow anon delete on portfolios"
  on public.portfolios
  for delete
  using (true);

-- ==============================================================================
-- SETUP SUPABASE STORAGE (BUCKET 'portfolio')
-- ==============================================================================

-- 5. Buat bucket storage publik bernama 'portfolio' (jika belum ada)
insert into storage.buckets (id, name, public)
values ('portfolio', 'portfolio', true)
on conflict (id) do update set public = true;

-- 6. Policy: Izinkan siapa saja melihat gambar publik di bucket 'portfolio'
create policy "Public Access to portfolio images"
  on storage.objects
  for select
  using (bucket_id = 'portfolio');

-- 7. Policy: Izinkan upload gambar ke bucket 'portfolio'
create policy "Allow uploads to portfolio bucket"
  on storage.objects
  for insert
  with check (bucket_id = 'portfolio');

-- 8. Policy: Izinkan hapus gambar di bucket 'portfolio'
create policy "Allow delete on portfolio bucket"
  on storage.objects
  for delete
  using (bucket_id = 'portfolio');
